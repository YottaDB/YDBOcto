#include <stdlib.h>
#include <assert.h> /* UNPACK_SQL_STATEMENT expands to assert() */

#include "octo.h"
#include "octo_types.h"

/* Does every column of this table take its value from the table's own row node?
 *
 * A column with no GLOBAL keyword of its own inherits the table's, so it is a piece of the row
 * node. If no column carries a GLOBAL keyword AND at least one non-key column actually reads
 * that node, then the set of nodes the schema declares for a row is exactly {the row node},
 * and two things follow:
 *
 *   - a row exists precisely when the row node carries a value, which is what
 *     "tmpl_tablejoin" turns into a QUIT guard inside the row FOR loop, and
 *   - AIM type 0 already indexes exactly those nodes, so the cross reference agrees with
 *     that scan without needing a decoupled record anchor (see "tmpl_physical_plan").
 *
 * A GLOBAL counts even on a column that also has EXTRACT. "recSubs" skips EXTRACT columns when
 * it measures how far the deepest column reaches below the row, because AIM cannot index a
 * computed column at all - but that is a different question from this one. An EXTRACT column
 * still says where its data is read from, and a row whose only data sits below the row node is
 * emphatically not a row defined by a value ON that node. TC032 is the case: DESCRIPTION is
 * EXTRACT over ^DD("IX",...,.1,...,0), one level below the row ^DD("IX",...,.1,...), which
 * carries no value of its own. Ignoring its GLOBAL here loses every row of that table.
 *
 * The test is deliberately conservative: a column whose GLOBAL happens to spell out the row
 * node itself would answer FALSE here and keep the anchor, which costs a little at run time
 * but stays correct. Deciding otherwise would mean parsing keys(...), nested parentheses and
 * quoted literals out of the GLOBAL string in C, which is the same thing "recSubs" avoids by
 * measuring column depth in M with $QLENGTH.
 */
boolean_t table_columns_all_on_row_node(SqlTable *table) {
	SqlColumn *start_column, *cur_column;
	boolean_t  reads_row_node;

	reads_row_node = FALSE;
	UNPACK_SQL_STATEMENT(start_column, table->columns, column);
	cur_column = start_column;
	do {
		/* table->columns also holds table-level constraint entries, which carry no column
		 * name and none of the keywords below; skip them the way get_key_columns() does, or
		 * a table-level PRIMARY KEY would be counted as a column that reads the row node.
		 */
		if (NULL == cur_column->columnName) {
			cur_column = cur_column->next;
			continue;
		}
		if (NULL != get_keyword(cur_column, OPTIONAL_GLOBAL)) {
			return FALSE;
		}
		/* A key column's value comes from a subscript, not from the node, and an EXTRACT
		 * column is computed. Neither reads the row node, so neither makes the row node a
		 * declared node.
		 */
		if ((NULL == get_keyword(cur_column, OPTIONAL_KEY_NUM)) && (NULL == get_keyword(cur_column, OPTIONAL_EXTRACT))) {
			reads_row_node = TRUE;
		}
		cur_column = cur_column->next;
	} while (cur_column != start_column);
	/* No GLOBAL anywhere, but nothing reads the row node either - so the schema declares NO
	 * value node at all and there is nothing to define row existence by. TITER01's
	 * cat_rec_titles is the case: every non-key column is EXTRACT over an M extrinsic, and
	 * the key it iterates is generated by an ITERATOR rather than read from the global, so
	 * the row node need not hold anything. Answering TRUE there makes the guard demand a
	 * value that was never promised, and the table returns no rows at all.
	 */
	return reads_row_node;
}
